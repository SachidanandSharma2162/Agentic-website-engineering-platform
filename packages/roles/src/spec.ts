import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { Project } from "@sdlc/core";
import { classifyRequest } from "./planner.ts";
import { selectModules, templateFor, type FeatureModule } from "./templates.ts";

/** Split a free-text request into candidate feature phrases (a draft for the operator to refine). */
export function extractFeatures(request: string): string[] {
  return request
    .split(/[,;\n]|\band\b|\bwith\b|\bincluding\b/i)
    .map((s) => s.trim().replace(/^(a|an|the)\s+/i, ""))
    .filter((s) => s.length > 3);
}

export interface SpecFile {
  path: string;
  content: string;
}

const BANNER = "> DRAFT generated by the platform from the raw request and the category template. Review and refine before the next gate.\n";

const moduleLine = (x: FeatureModule): string => `- **${x.title}** (${x.id}): ${x.description}${x.requires.length ? ` Needs: ${x.requires.join(", ")}.` : ""}`;

/**
 * Draft specification documents derived from the request and the category template. They are clearly labelled as
 * drafts; the operator replaces them with reviewed content before Gate A. The architecture and design drafts use
 * ".draft" file names on purpose: the real `docs/architecture.md` and design artifacts must be written (and reviewed)
 * by the operator, so an unreviewed draft can never satisfy those tasks.
 */
export function draftSpecFiles(p: Project): SpecFile[] {
  const classification = classifyRequest(p.request);
  const tpl = templateFor(p.category);
  const sel = selectModules(p.request, tpl);
  const phrases = extractFeatures(p.request);
  const planned = [...sel.mvp, ...sel.requested];
  const phraseList = phrases.length ? phrases.map((f, i) => `- R${i + 1}: ${f}`).join("\n") : "- (none extracted; operator must define)";
  const gateEList = sel.gateE.length ? sel.gateE.map((g) => `- **${g.module}**: ${g.reason}`).join("\n") : "- none identified from the request and template";

  const requirements = `# Requirements: ${p.name}

${BANNER}
## Request

${p.request}

## Classification

- Category: ${p.category}
- Complexity: ${p.complexity}${classification.signals.length ? ` (signals: ${classification.signals.join(", ")})` : ""}
- Needs a backend: ${sel.capabilities.includes("backend") || tpl.architecture.backend ? "yes (confirm at Gate A)" : "no (client-only or static is enough)"}
- Capabilities required by planned modules: ${sel.capabilities.join(", ") || "none"}

## Audience

${tpl.audience}

## Key user journeys

${tpl.journeys.map((j) => `- ${j}`).join("\n")}

## What the request literally asks for

${phraseList}

## Feature modules

### MVP
${sel.mvp.map(moduleLine).join("\n") || "- (none)"}

### Requested in the text but not in the category's default MVP (confirm)
${sel.requested.map(moduleLine).join("\n") || "- (none)"}

### Optional
${sel.optional.map(moduleLine).join("\n") || "- (none)"}

### Future scope (not built)
${sel.future.map(moduleLine).join("\n") || "- (none)"}

## Non-functional requirements

${tpl.nonFunctional.map((n) => `- ${n}`).join("\n")}

## Actions that will need explicit approval (Gate E)

${gateEList}

## Assumptions

- To be confirmed at Gate A.
`;

  const stories = `# User stories: ${p.name}

${BANNER}
${planned.map((x, i) => `- US${i + 1} (${x.id}): As a visitor or user I can use ${x.title.toLowerCase()}: ${x.description}`).join("\n") || "- (none)"}
`;

  const acceptance = `# Acceptance criteria: ${p.name}

${BANNER}
Each criterion is a template and must become a concrete automated test (unit, component, API or Playwright) with the verification method named.

${planned.map((x) => `## ${x.title} (${x.id})\n${x.acceptance.map((a, i) => `- AC-${x.id}-${i + 1}: ${a} [verified by: TBD]`).join("\n")}`).join("\n\n") || "- (none)"}

## Cross-cutting
- AC-A11Y: axe reports no serious or critical violations on every route and key state.
- AC-RESP: no horizontal scroll or overlap at 375, 768 and 1280 px.
- AC-SEC: dependency audit has no high or critical findings; no secrets in client code.
- AC-DEPLOY: the live URL returns 200 on every route and passes the same E2E suite.
`;

  const plan = `# Project plan: ${p.name}

${BANNER}
See the task graph in the platform state store (\`sdlc status ${p.id}\`). Phases: spec, architecture, design (Gate A), implement (Gate B), tests, quality, security, release (Gate C), deploy (Gate D), smoke, handover.
`;

  const risks = `# Risk register: ${p.name}

${BANNER}
| Risk | Severity | Mitigation | Status |
|---|---|---|---|
| Requirements ambiguity | medium | Clarify at Gate A | open |
| Free-tier limits differ from assumptions | medium | Verify against official docs before deploy | open |
${tpl.risks.map((r) => `| ${r.risk} | ${r.severity} | ${r.mitigation} | open |`).join("\n")}
${sel.gateE.map((g) => `| ${g.module} needs Gate E approval | high | ${g.reason} | open |`).join("\n")}
`;

  const architecture = `# Architecture (draft starting point): ${p.name}

${BANNER}
Write the reviewed version as \`docs/architecture.md\`. This draft does not satisfy the architecture task.

- Style: ${tpl.architecture.style}
- Suggested stack: ${tpl.architecture.stack}
- Backend: ${tpl.architecture.backend ? "yes" : "no"}; data store: ${tpl.architecture.database}
- Notes: ${tpl.architecture.notes}
- Capabilities needed by the planned modules: ${sel.capabilities.join(", ") || "none"}

Verify current pricing, free-tier limits and runtime support for every service before choosing it. Choose a modular monolith unless a requirement justifies more.
`;

  const design = `# Design brief (draft starting point): ${p.name}

${BANNER}
Write the real design system and a runnable prototype for Gate B. This draft does not satisfy the design task.

- Priority for this category: ${tpl.design.priority}
- Tone: ${tpl.design.tone}
- Layout pattern: ${tpl.design.layout}
- Typography direction: ${tpl.design.typography}

Rules: define colour tokens and compute WCAG contrast for every text/background pair before building; use a distinctive identity, not a generic template; specify hover, focus, loading, empty, error and success states; respect prefers-reduced-motion.
`;

  return [
    { path: "docs/requirements.md", content: requirements },
    { path: "docs/user-stories.md", content: stories },
    { path: "docs/acceptance-criteria.md", content: acceptance },
    { path: "docs/project-plan.md", content: plan },
    { path: "docs/risk-register.md", content: risks },
    { path: "docs/architecture.draft.md", content: architecture },
    { path: "docs/design-brief.draft.md", content: design },
  ];
}

/** Writes draft files that do not exist yet. Never overwrites existing work. Returns the paths written. */
export function writeDraftSpec(p: Project): { written: string[]; skipped: string[] } {
  const written: string[] = [];
  const skipped: string[] = [];
  for (const f of draftSpecFiles(p)) {
    const abs = join(p.workDir, f.path);
    if (existsSync(abs)) {
      skipped.push(f.path);
      continue;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, f.content, "utf8");
    written.push(f.path);
  }
  return { written, skipped };
}
