import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { Project } from "@sdlc/core";

/** Split a free-text request into candidate feature phrases (a draft for the operator to refine). */
export function extractFeatures(request: string): string[] {
  return request
    .split(/[,;\n]|\band\b|\bwith\b|\bincluding\b/i)
    .map((s) => s.trim().replace(/^(a|an|the)\s+/i, ""))
    .filter((s) => s.length > 3);
}

export interface SpecFile {
  path: string;
  content: string;
}

/**
 * Draft specification documents derived heuristically from the request. They are clearly labelled as
 * drafts; the operator is expected to replace them with reviewed content before Gate A.
 */
export function draftSpecFiles(p: Project): SpecFile[] {
  const features = extractFeatures(p.request);
  const banner = "> DRAFT generated by the heuristic planner from the raw request. Review and refine before Gate A.\n";
  const featureList = features.length ? features.map((f, i) => `- F${i + 1}: ${f}`).join("\n") : "- (none extracted; operator must define)";
  return [
    {
      path: "docs/requirements.md",
      content: `# Requirements: ${p.name}\n\n${banner}\n## Request\n\n${p.request}\n\n## Classification\n\n- Category: ${p.category}\n- Complexity: ${p.complexity}\n\n## Candidate features\n\n${featureList}\n\n## Assumptions\n\n- To be confirmed at Gate A.\n`,
    },
    {
      path: "docs/user-stories.md",
      content: `# User stories: ${p.name}\n\n${banner}\n${features.map((f, i) => `- US${i + 1}: As a visitor I can ${f}, so that I get value from the site.`).join("\n") || "- (none)"}\n`,
    },
    {
      path: "docs/acceptance-criteria.md",
      content: `# Acceptance criteria: ${p.name}\n\n${banner}\n${features.map((f, i) => `- AC${i + 1} (F${i + 1}): [verifiable test needed] ${f}`).join("\n") || "- (none)"}\n\nEvery feature needs at least one automated, verifiable criterion before Gate A.\n`,
    },
    {
      path: "docs/project-plan.md",
      content: `# Project plan: ${p.name}\n\n${banner}\nSee the task graph in the platform state store. Phases: spec, architecture, design (Gate A), implement (Gate B), tests, quality, security, release (Gate C), deploy (Gate D), smoke, handover.\n`,
    },
    {
      path: "docs/risk-register.md",
      content: `# Risk register: ${p.name}\n\n${banner}\n| Risk | Severity | Mitigation | Status |\n|---|---|---|---|\n| Requirements ambiguity | medium | Clarify at Gate A | open |\n| Free-tier limits differ from assumptions | medium | Verify against official docs before deploy | open |\n`,
    },
  ];
}

/** Writes draft files that do not exist yet. Never overwrites existing work. Returns the paths written. */
export function writeDraftSpec(p: Project): { written: string[]; skipped: string[] } {
  const written: string[] = [];
  const skipped: string[] = [];
  for (const f of draftSpecFiles(p)) {
    const abs = join(p.workDir, f.path);
    if (existsSync(abs)) {
      skipped.push(f.path);
      continue;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, f.content, "utf8");
    written.push(f.path);
  }
  return { written, skipped };
}
